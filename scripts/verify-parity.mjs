import { createHash } from 'node:crypto'
import { readdir, readFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

async function inventory(root, dir = root, result = new Map()) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) await inventory(root, path, result)
    else result.set(relative(root, path), createHash('sha256').update(await readFile(path)).digest('hex'))
  }
  return result
}

const web = await inventory('dist')
for (const root of ['ios/App/App/public', 'android/app/src/main/assets/public']) {
  const native = await inventory(root)
  // These files are injected by Capacitor, rather than generated by Vite.
  const injected = new Set(['cordova.js', 'cordova_plugins.js'])
  const different = [...web].filter(([path, hash]) => native.get(path) !== hash).map(([path]) => path)
  const extra = [...native.keys()].filter((path) => !web.has(path) && !injected.has(path))
  if (different.length || extra.length) {
    throw new Error(`${root}: differing/missing=${different.join(',')}; unexpected=${extra.join(',')}. Run npm run sync.`)
  }
  console.log(`PASS ${root}: ${web.size} web files match dist byte-for-byte (SHA-256)`)
}
