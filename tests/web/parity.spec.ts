import { expect, test } from '@playwright/test'

test('共享页面导航、商城、模拟配网与登录持久化', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  // Bundled fonts and assets must work without any external network.
  await page.route('**/*', (route) => route.request().url().startsWith('http://127.0.0.1:4173/') ? route.continue() : route.abort())
  await page.goto('http://127.0.0.1:4173')
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeEnabled()
  await expect(page.locator('input').first()).toHaveValue('13800138000')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '母舰' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('01-home.png') })
  await page.getByRole('button', { name: '母舰' }).click()
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('02-settings.png') })
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '探针', exact: true }).click()
  await expect(page.getByRole('button', { name: '下一个型号' }).first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('03-mall.png') })
  await page.getByRole('button', { name: '下一个型号' }).first().click()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '扫码', exact: true }).click()
  await expect(page.getByRole('heading', { name: '扫码配网', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '扫描产品机身二维码' }).click()
  await expect(page.getByPlaceholder('请输入 WiFi 名称')).toBeVisible()
  await page.getByPlaceholder('请输入 WiFi 名称').fill('PetSoul_2.4G')
  await page.getByPlaceholder('至少 8 位').fill('petsoul-demo')
  await page.getByRole('button', { name: '开始配网', exact: true }).click()
  await expect(page.getByRole('heading', { name: '配网并绑定成功' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('04-bound.png') })
  await page.reload()
  await expect(page.getByRole('button', { name: '母舰' })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('pet-smart-app:account') ?? 'null')?.identifier)).toBe('13800138000')
  expect(errors).toEqual([])
})
